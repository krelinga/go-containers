#!/usr/bin/env bash
# Regenerate bench.txt. Numbers in RESULTS.md come from this script.
#
#   ./run.sh                      # default sampling
#   COUNT=20 BENCHTIME=1s ./run.sh
#
# benchstat (optional, for the summary table):
#   go install golang.org/x/perf/cmd/benchstat@latest
set -euo pipefail
cd "$(dirname "$0")"

COUNT=${COUNT:-10}
BENCHTIME=${BENCHTIME:-200ms}
OUT=${OUT:-bench.txt}

{
  echo "# generated by run.sh -- do not hand-edit"
  echo "# date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# go: $(go version)"
  echo "# cpu-model: $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | xargs)"
  echo "# nproc: $(nproc)"
  echo "# virt: $(systemd-detect-virt 2>/dev/null || echo unknown)"
  echo "# count: ${COUNT}  benchtime: ${BENCHTIME}"
  echo "#"
  echo "# NOTE: absolute timings are machine-specific and understate memory"
  echo "# bandwidth under virtualization. Ratios between benchmarks are the"
  echo "# durable result; re-run on target hardware before citing absolutes."
  echo
} > "$OUT"

go test -run='^$' -bench=. -benchmem \
  -count="$COUNT" -benchtime="$BENCHTIME" -timeout=30m | tee -a "$OUT"

if command -v benchstat >/dev/null 2>&1; then
  echo
  echo "=== benchstat ==="
  benchstat "$OUT"
else
  echo
  echo "benchstat not installed; skipping summary." >&2
  echo "  go install golang.org/x/perf/cmd/benchstat@latest" >&2
fi
